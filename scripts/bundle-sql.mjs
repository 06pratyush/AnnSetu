// Joins the migrations into supabase/setup.sql, ready to paste into the Supabase SQL editor, and
// writes the copies demo mode loads in the browser: public/demo/{stubs.sql, setup.sql, manifest.json}.
// Run: npm run db:bundle (also runs before every dev and build).
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const dir = path.join(root, "supabase/migrations");
const parts = readdirSync(dir)
  .filter((f) => f.endsWith(".sql"))
  .sort()
  .map((f) => `-- ===== ${f} =====\n\n${readFileSync(path.join(dir, f), "utf8").trim()}\n`);
const header = `-- AnnSetu database setup: every migration in order.
-- Paste this whole file into Supabase → SQL Editor → New query, then Run. Run it once, on a new project.
-- Generated by "npm run db:bundle"; edit the files in supabase/migrations instead.

`;
const setup = header + parts.join("\n");
writeFileSync(path.join(root, "supabase/setup.sql"), setup);

// Demo mode: the same SQL, run by PGlite in the browser after the stand-ins for Supabase's schemas.
const stubs = readFileSync(path.join(root, "supabase/demo/stubs.sql"), "utf8");
const demoDir = path.join(root, "public/demo");
mkdirSync(demoDir, { recursive: true });
writeFileSync(path.join(demoDir, "stubs.sql"), stubs);
writeFileSync(path.join(demoDir, "setup.sql"), setup);
// A new schema means a new demo database: the version names the browser's IndexedDB store.
const version = createHash("sha256").update(stubs).update(setup).digest("hex").slice(0, 12);
writeFileSync(path.join(demoDir, "manifest.json"), JSON.stringify({ version }) + "\n");

console.log(`supabase/setup.sql: ${parts.length} migrations; demo database ${version}`);
