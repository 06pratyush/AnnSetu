// Joins the migrations into supabase/setup.sql, ready to paste into the Supabase SQL editor.
// Run: npm run db:bundle
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const dir = path.join(root, "supabase/migrations");
const parts = readdirSync(dir)
  .filter((f) => f.endsWith(".sql"))
  .sort()
  .map((f) => `-- ===== ${f} =====\n\n${readFileSync(path.join(dir, f), "utf8").trim()}\n`);
const header = `-- AnnSetu database setup: every migration in order.
-- Paste this whole file into Supabase → SQL Editor → New query, then Run. Run it once, on a new project.
-- Generated by "npm run db:bundle"; edit the files in supabase/migrations instead.

`;
writeFileSync(path.join(root, "supabase/setup.sql"), header + parts.join("\n"));
console.log(`supabase/setup.sql: ${parts.length} migrations`);
